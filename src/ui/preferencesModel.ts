export type TranslationKey = keyof typeof th;
export const translations = {th,en};
export function translate(language: Language, key: TranslationKey, args?: Record<string,string|number>):string {
  const value = translations[language][key];
  return args ? value.replace(/\{(\w+)\}/g, (_match,name:string) => String(args[name]??'{'+name+'}')) : value;
}
export function parsePreferences(value: string | null): Preferences {
  if (!value) return DEFAULT_PREFERENCES;
  try {
    const data: unknown = JSON.parse(value);
    if (!data || typeof data !== 'object') return DEFAULT_PREFERENCES;
    const d = data as Record<string, unknown>;
    return {
      theme: d.theme === 'dark' ? 'dark' : 'light',
      language: d.language === 'en' ? 'en' : 'th',
    };
  } catch { return DEFAULT_PREFERENCES; }
}
